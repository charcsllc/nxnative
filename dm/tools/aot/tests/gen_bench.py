#!/usr/bin/env python3
"""A game-shaped benchmark module for the pack stage's throughput (README.md, "Pack throughput"): many functions of the sizes and kinds game code
has (most of them small: accessors, arithmetic; some with loops, switches compiled to jump tables, calls, calls through a table of function
pointers, floating point and NEON vectors, struct copies; a few large), generated from a seed, built as an NRO with the corpus's run time and
the corpus's clang flags, with unwind tables (FDEs) and no exported symbols but main's. No game files: the corpus (dm/tools/aot/corpus) is
too small and too unlike a game (switch-gcc's 51,097 instructions are 63 functions of mostly straight-line checks) to measure per-function
costs or to show what grows faster than the module.

The program runs: main calls every function through drivers, a bounded call depth keeps recursion finite, and it prints one checksum line, so a
pack of it can be checked against dynarmic (nxaot_run) as the corpus is.

  gen_bench.py --functions N [--seed S] [--unbounded-switches] <out dir>
      writes <out dir>/bench.c, bench.elf, bench.nro (in the nxnative-aot image: clang-18, ld.lld-18)
"""
import argparse
import os
import random
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
RT = os.path.join(HERE, '..', 'corpus', 'rt')
ELF2NRO = os.path.join(HERE, 'elf2nro.py')
CFLAGS = ['--target=aarch64-none-elf', '-O2', '-mcpu=cortex-a57', '-mno-outline-atomics', '-std=gnu11', '-ffreestanding', '-fPIE',
          '-fno-stack-protector', '-ffp-contract=off', '-fno-math-errno', '-fasynchronous-unwind-tables', '-I', RT]
LDFLAGS = ['-pie', '--no-dynamic-linker', '--eh-frame-hdr', '--export-dynamic', '--hash-style=sysv', '--build-id=sha1', '-z', 'text', '-z',
           'max-page-size=0x1000', '-T', os.path.join(RT, 'nro.ld'), '-z', 'pack-relative-relocs']

HEADER = r'''// Generated by dm/tools/aot/tests/gen_bench.py (seed %(seed)d, %(n)d functions): a game-shaped benchmark of nxaot's pack stage
#include "rt.h"

typedef float v4f __attribute__((vector_size(16)));
typedef uint32_t v4u __attribute__((vector_size(16)));
typedef struct {
    uint64_t id, link;
    uint32_t flags;
    int32_t hp;
    float pos[4], vel[4];
    uint8_t name[16];
} obj_t;
typedef uint64_t (*fn_t)(uint64_t, uint64_t, unsigned);

static obj_t objs[64];
static uint64_t mem[1024];
static float fbuf[256];
'''


def c64(r):
    return '0x%016xull' % r.getrandbits(64)


class Gen:
    def __init__(self, n, seed, unbounded=False):
        self.n = n
        self.unbounded = unbounded
        self.r = random.Random(seed)
        self.table = 1 << max(4, (n // 4).bit_length() - 1)  # a table of function pointers about a quarter of the functions long

    def stmt(self, i, depth):
        r = self.r
        k = r.randrange(100)
        if k < 18:
            return f'    a = a * {c64(r)} + (b ^ {c64(r)});'
        if k < 28:
            s = r.randrange(1, 63)
            return f'    b = (b << {s}) | (b >> {64 - s}); a ^= b + {r.randrange(1, 1 << 16)};'
        if k < 38:
            return f'    if (a & {1 << r.randrange(0, 40)}ull) a += b * {r.randrange(3, 99)}; else b -= a >> {r.randrange(1, 9)};'
        if k < 48:
            return (f'    mem[(a + {r.randrange(1024)}) & 1023] = b; b += mem[(b + {r.randrange(1024)}) & 1023];')
        if k < 58:
            return ('    { obj_t *o = &objs[a & 63]; o->hp = (int32_t)((uint32_t)o->hp + (uint32_t)b); o->flags |= 1u << (b & 31); '
                    f'a ^= o->id + o->link; o->link = b + {r.randrange(1, 1000)}; }}')
        if k < 64:
            return (f'    for (unsigned j = 0; j < (b & 15) + {r.randrange(2, 8)}; ++j) a = a * 31 + mem[(j * {r.randrange(1, 32)} + b) & 1023];')
        if k < 70:
            # A switch over a field with a range check before its table, as on an enum; with --unbounded-switches a switch over a remainder
            # with every value a case, which has no check: its index is a multiply-high nothing bounds (README.md, "Module loader and
            # discovery"), so discovery leaves its br to the dispatcher after trying every region (a stress case of discovery's cost)
            cases = r.randrange(5, 24)
            body = ' '.join(f'case {c}: b += {c64(r)}; a ^= b >> {r.randrange(1, 60)}; break;' for c in range(cases))
            if self.unbounded:
                return f'    switch (a % {cases}) {{ {body} default: b ^= a; }}'
            return f'    switch ((a >> {r.randrange(0, 40)}) & 31) {{ {body} default: b ^= a; }}'
        if k < 76:
            return ('    { float x = (float)(a & 0xffff) * 0.25f, y = (float)(b & 0xffff) * 0.5f; '
                    f'float q = __builtin_sqrtf(x * x + y * y + {r.randrange(1, 9)}.0f); fbuf[a & 255] = q; a += (uint64_t)(q * 16.0f); }}')
        if k < 80:
            return ('    { obj_t *o = &objs[b & 63]; v4f p = {o->pos[0], o->pos[1], o->pos[2], (float)(a & 255)}; '
                    'v4f v = {o->vel[0], o->vel[1], o->vel[2], 1.0f}; p = p + v * 0.5f; '
                    'for (int c = 0; c < 4; ++c) o->pos[c] = p[c] - (float)(int)p[c]; v4u u = (v4u)p; a += u[0] ^ u[3]; }')
        if k < 84:
            return f'    {{ obj_t t = objs[a & 63]; t.hp ^= (int32_t)(b & 0xffff); t.id += {r.randrange(1, 1 << 20)}; objs[b & 63] = t; }}'
        if k < 87:
            return ('    { uint64_t h = 5381; const uint8_t *s = objs[a & 63].name; '
                    'for (unsigned j = 0; j < 16; ++j) h = h * 33 + s[j]; b ^= h; }')
        if k < 96:
            j = r.randrange(self.n)
            return f'    if (d) a += f{j}(a ^ {c64(r)}, b + {r.randrange(1, 1 << 30)}, d - 1);'
        return f'    if (d) b ^= ftab[(a ^ b) & {self.table - 1}](a, b + {r.randrange(1, 1 << 20)}, d - 1);'

    def function(self, i):
        r = self.r
        size = r.random()
        count = r.randrange(1, 4) if size < 0.70 else r.randrange(4, 13) if size < 0.95 else r.randrange(20, 61)
        body = '\n'.join(self.stmt(i, 0) for _ in range(count))
        return f'static RT_NOINLINE uint64_t f{i}(uint64_t a, uint64_t b, unsigned d) {{\n{body}\n    return a ^ (b << 1);\n}}\n'

    def source(self, seed):
        out = [HEADER % {'seed': seed, 'n': self.n}]
        out.append(''.join(f'static uint64_t f{i}(uint64_t, uint64_t, unsigned);\n' for i in range(self.n)))
        members = [self.r.randrange(self.n) for _ in range(self.table)]
        out.append('static fn_t const ftab[%d] = {%s};\n' % (self.table, ', '.join(f'f{m}' for m in members)))
        for i in range(self.n):
            out.append(self.function(i))
        drivers = []
        for start in range(0, self.n, 64):
            name = f'drive{start // 64}'
            calls = '\n'.join(f'    h = rt_mix(h, f{i}(h + {i}, h ^ {c64(self.r)}, 2));' for i in range(start, min(start + 64, self.n)))
            out.append(f'static RT_NOINLINE uint64_t {name}(uint64_t h) {{\n{calls}\n    return h;\n}}\n')
            drivers.append(name)
        init = ('    for (unsigned i = 0; i < 64; ++i) { objs[i].id = i * 0x9e3779b97f4a7c15ull; objs[i].hp = (int32_t)i; '
                'for (unsigned c = 0; c < 4; ++c) { objs[i].pos[c] = (float)(i + c); objs[i].vel[c] = (float)c * 0.5f; } '
                'for (unsigned c = 0; c < 16; ++c) objs[i].name[c] = (uint8_t)(i * 7 + c); }\n'
                '    for (unsigned i = 0; i < 1024; ++i) mem[i] = i * 0xbf58476d1ce4e5b9ull;\n')
        run = '\n'.join(f'    h = {d}(h);' for d in drivers)
        out.append(f'int main(void) {{\n{init}    uint64_t h = RT_MIX_INIT;\n{run}\n    rt_note("bench", h, 16);\n    return rt_finish();\n}}\n')
        return ''.join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument('out')
    ap.add_argument('--functions', type=int, default=4000)
    ap.add_argument('--seed', type=int, default=1)
    ap.add_argument('--unbounded-switches', action='store_true', help='switches over a remainder, with no range check (discovery stress)')
    ap.add_argument('--cc', default='clang-18')
    ap.add_argument('--ld', default='ld.lld-18')
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    src = os.path.join(a.out, 'bench.c')
    with open(src, 'w') as f:
        f.write(Gen(a.functions, a.seed, a.unbounded_switches).source(a.seed))
    objs = []
    for s in (os.path.join(RT, 'crt0.S'), os.path.join(RT, 'mem.S'), os.path.join(RT, 'rt.c'), src):
        o = os.path.join(a.out, os.path.basename(s).replace('.', '_') + '.o')
        subprocess.run([a.cc] + CFLAGS + ['-c', s, '-o', o], check=True)
        objs.append(o)
    elf = os.path.join(a.out, 'bench.elf')
    subprocess.run([a.ld] + LDFLAGS + ['-o', elf] + objs, check=True)
    subprocess.run([sys.executable, ELF2NRO, elf, os.path.join(a.out, 'bench.nro')], check=True)
    print(f'gen_bench.py: {a.functions} functions (seed {a.seed}) in {os.path.join(a.out, "bench.nro")}')


if __name__ == '__main__':
    main()
