def a_cmpi(rn, imm): return 0xF100001F | imm << 10 | rn << 5
def a_cmp(rn, rm): return 0xEB00001F | rm << 16 | rn << 5
def a_ldr(rt, rn, off): return 0xF9400000 | (off // 8) << 10 | rn << 5 | rt
def a_str(rt, rn, off): return 0xF9000000 | (off // 8) << 10 | rn << 5 | rt
