#!/usr/bin/env python3
"""A game-shaped benchmark module for the pack stage's throughput (README.md, "Pack throughput"): many functions of the sizes and kinds game code
has (most of them small: accessors, arithmetic; some with loops, switches compiled to jump tables, calls, calls through a table of function
pointers, floating point and NEON vectors, struct copies; a few large), generated from a seed, built as an NRO with the corpus's run time and
the corpus's clang flags, with unwind tables (FDEs) and no exported symbols but main's. No game files: the corpus (dm/tools/aot/corpus) is
too small and too unlike a game (switch-gcc's 51,097 instructions are 63 functions of mostly straight-line checks) to measure per-function
costs or to show what grows faster than the module.

The program runs: main calls every function through drivers, a bounded call depth keeps recursion finite, and it prints one checksum line, so a
pack of it can be checked against dynarmic (nxaot_run) as the corpus is.

  gen_bench.py --functions N [--seed S] [--unbounded-switches] [--data-rows R --nxaot <nxaot>] <out dir>
      writes <out dir>/bench.c, bench.elf, bench.nro (in the nxnative-aot image: clang-18, ld.lld-18); with --data-rows also the behaviour
      image <out dir>/rows/bench.image.bin (`nxaot image`) with R more data rows in its manifest bench.aot.tsv: one word each, evenly spaced
      over the text (they cut the code they cover: a stress case of the loader's data blocks, Image::InData, not a program that runs)
  gen_bench.py --direct --functions N [--instructions M] [--seed S] [--profile-percent P] <out dir>
      writes the words of the same kinds of statements directly, without clang, at any size (README.md, "Memory at scale"): the behaviour image
      <out dir>/main.image.bin and its manifest main.aot.tsv, as patch_nso.py --aot writes them for a game's NSO, about M instructions in all
      (default 52 per function: Monster Hunter Rise's `main` is about 31 million in about 600,000 functions); with --profile-percent also
      main.profile, one sample at the entry of P % of the functions (nxaot build --profile). Not a program that runs (below, "--direct")
"""
