#!/bin/sh
# The SPIR-V of the Vulkan backend's own shaders (dm/gfx/hostvk/shaders, docs/design/vulkan-backend.md 2.7) and of its GPU tests' shaders (dm/gfx/tests/vk/shaders), compiled by
# glslangValidator for Vulkan 1.3, validated with spirv-val and written as C arrays into <folder>/gen/<name>_<stage>.h (array <name>_<stage>_spv). The headers are committed, so
# building needs no glslang. Variants: clear.frag for each colour slot and value type (clear_frag.h: clear_frag_s<slot>_k<kind>_spv), q.comp for the four counter kernels of
# nvn_builtin.h (q_val0.h, q_val8.h, q_dlt0.h, q_dlt8.h).
#   sh dm/gfx/hostvk/shaders/gen_spirv.sh           regenerate the headers (run it after editing a shader)
#   sh dm/gfx/hostvk/shaders/gen_spirv.sh --check   rebuild into a temporary folder and compare byte for byte with the committed headers: exit 0 when identical, 1 on a difference,
#                                                   77 (skipped) when glslang or spirv-val is missing or is not the version the headers were made with
# Both run in the nxnative-build image (docker/README.md), from the repository root or anywhere:
#   docker run --rm --user "$(id -u):$(id -g)" -e HOME=/tmp -v "$(pwd):/src" -w /src nxnative-build sh dm/gfx/hostvk/shaders/gen_spirv.sh
set -eu
here=$(cd "$(dirname "$0")" && pwd)
repo=$(cd "$here/../../../.." && pwd)
check=0
[ "${1:-}" = "--check" ] && check=1
if ! command -v glslangValidator >/dev/null 2>&1 || ! command -v spirv-val >/dev/null 2>&1; then
    echo "glslangValidator and spirv-val are needed (the nxnative-build image has them)" >&2
    [ $check = 1 ] && exit 77
    exit 2
fi
version=$(glslangValidator --version | sed -n 's/^Glslang Version: //p' | head -n 1)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT

# compile <source> <array name> <output header, relative to the gen folder> [-D...]: appends one array to the header in $tmp
compile() {
    src=$1; var=$2; out=$3; shift 3
    rel=${src#"$repo"/}
    glslangValidator -V --target-env vulkan1.3 "$@" -o "$tmp/$var.spv" "$src" >"$tmp/log" 2>&1 || { cat "$tmp/log" >&2; echo "glslang failed on $rel $*" >&2; exit 2; }
    spirv-val --target-env vulkan1.3 "$tmp/$var.spv" || { echo "spirv-val refused $rel $*" >&2; exit 2; }
    glslangValidator -V --target-env vulkan1.3 "$@" --vn "$var" -o "$tmp/$var.txt" "$src" >/dev/null
    if [ ! -f "$tmp/out/$out" ]; then
        mkdir -p "$(dirname "$tmp/out/$out")"
        echo "// Generated by dm/gfx/hostvk/shaders/gen_spirv.sh (glslang $version, --target-env vulkan1.3); do not edit. The shader's source is beside the gen folder" > "$tmp/out/$out"
        echo "#pragma once" >> "$tmp/out/$out"
        echo "#include <stdint.h>" >> "$tmp/out/$out"
    fi
    echo "// $var: $(basename "$src")${*:+ $*}, $(wc -c < "$tmp/$var.spv" | tr -d ' ') bytes" >> "$tmp/out/$out"
    grep -v '^[[:space:]]*//' "$tmp/$var.txt" | grep -v 'pragma once' | sed 's/^const uint32_t/static const uint32_t/' >> "$tmp/out/$out"
}
# every shader of a folder: <name>.<stage> → gen/<name>_<stage>.h; the variant files by their rules
folder() {
    dir=$1; key=$2
    for src in "$dir"/*.vert "$dir"/*.frag "$dir"/*.comp "$dir"/*.geom "$dir"/*.tesc "$dir"/*.tese; do
        [ -f "$src" ] || continue
        base=$(basename "$src"); name=${base%.*}; stage=${base##*.}
        case "$key/$base" in
            hostvk/clear.frag)
                for s in 0 1 2 3 4 5 6 7; do for k in 0 1 2; do compile "$src" "clear_frag_s${s}_k${k}_spv" "$key/clear_frag.h" -DSLOT=$s -DKIND=$k; done; done ;;
            hostvk/q.comp)
                n=0; for q in q_val0 q_val8 q_dlt0 q_dlt8; do compile "$src" "${q}_spv" "$key/$q.h" -DKERNEL=$n; n=$((n + 1)); done ;;
            *) compile "$src" "${name}_${stage}_spv" "$key/${name}_${stage}.h" ;;
        esac
    done
}
mkdir -p "$tmp/out"
folder "$here" hostvk
folder "$repo/dm/gfx/tests/vk/shaders" tests
status=0
for h in "$tmp"/out/hostvk/*.h "$tmp"/out/tests/*.h; do
    [ -f "$h" ] || continue
    case "$h" in */out/hostvk/*) dest="$here/gen/$(basename "$h")" ;; *) dest="$repo/dm/gfx/tests/vk/shaders/gen/$(basename "$h")" ;; esac
    if [ $check = 1 ]; then
        if [ ! -f "$dest" ]; then echo "missing: ${dest#"$repo"/}"; status=1
        elif ! cmp -s "$h" "$dest"; then
            committed=$(sed -n '1s/.*(glslang \([^,]*\),.*/\1/p' "$dest")
            if [ "$committed" != "$version" ]; then echo "skipped: ${dest#"$repo"/} was made with glslang $committed, this is $version"; exit 77; fi
            echo "differs: ${dest#"$repo"/} (rebuild with dm/gfx/hostvk/shaders/gen_spirv.sh)"; status=1
        else echo "identical: ${dest#"$repo"/}"; fi
    else
        mkdir -p "$(dirname "$dest")"; cp "$h" "$dest"; echo "wrote ${dest#"$repo"/}"
    fi
done
if [ $check = 1 ]; then   # a committed header no shader makes any more
    for dest in "$here"/gen/*.h "$repo"/dm/gfx/tests/vk/shaders/gen/*.h; do
        [ -f "$dest" ] || continue
        case "$dest" in "$here"/gen/*) k=hostvk ;; *) k=tests ;; esac
        [ -f "$tmp/out/$k/$(basename "$dest")" ] || { echo "stale: ${dest#"$repo"/} (no shader makes it)"; status=1; }
    done
    [ $status = 0 ] && echo "the shader headers rebuild byte for byte (glslang $version)"
fi
exit $status
