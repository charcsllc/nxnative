#!/bin/sh
# Regenerates the SPIR-V the hostvk tests embed, from the GLSL compute shaders beside this script (<name>.comp -> <name>.h, an array <name>_spv), and validates it with
# spirv-val. The blobs are committed, so building the tests needs no glslang; run this after editing a .comp, in the nxnative-build image (docker/README.md), from the repository root:
#   docker run --rm --user "$(id -u):$(id -g)" -e HOME=/tmp -v "$(pwd):/src" -w /src nxnative-build sh dm/gfx/hostvk/tests/gen_spirv.sh
set -eu
here=$(cd "$(dirname "$0")" && pwd)
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
command -v glslangValidator >/dev/null && command -v spirv-val >/dev/null || { echo "glslangValidator and spirv-val are needed (the nxnative-build image has them)" >&2; exit 2; }
for src in "$here"/*.comp; do
    name=$(basename "$src" .comp)
    glslangValidator -V --target-env vulkan1.3 -o "$tmp/$name.spv" "$src" >/dev/null
    spirv-val --target-env vulkan1.3 "$tmp/$name.spv"
    {
        echo "// Generated by dm/gfx/hostvk/tests/gen_spirv.sh from $name.comp ($(glslangValidator --version | sed -n 's/^Glslang Version: //p' | head -n 1), --target-env vulkan1.3); do not edit"
        glslangValidator -V --target-env vulkan1.3 --vn "${name}_spv" -o "$tmp/$name.h" "$src" >/dev/null
        cat "$tmp/$name.h"
    } > "$here/$name.h"
    echo "wrote $here/$name.h: $(wc -c < "$tmp/$name.spv") bytes of SPIR-V, spirv-val clean"
done
